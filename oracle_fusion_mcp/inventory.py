"""Inventory / shipping shortcuts. knowledge/inventory-organizations.md, carriers.md."""
from __future__ import annotations

from .generic import create_checked, q_str, rest_get


def find_inventory_org(name_or_code: str = "", limit: int = 50) -> dict:
    """Find inventory organizations by part of the code or name (empty = all)."""
    q = (f"OrganizationCode LIKE {q_str('%' + name_or_code + '%')} or "
         f"OrganizationName LIKE {q_str('%' + name_or_code + '%')}") if name_or_code else ""
    return rest_get("inventoryOrganizations", q=q, fields="OrganizationId,OrganizationCode,OrganizationName,LocationId",
                    limit=limit, all_pages=not name_or_code)


def create_carrier(carrier_name: str, extra: dict | None = None, dry_run: bool = True, confirm_prod: str = "",
                   allow_duplicate: bool = False) -> dict:
    """Create a carrier (step 1). To 'enable it on an org': add_carrier_ship_method, then enable_ship_method_on_org."""
    return create_checked("carriers", {"CarrierName": carrier_name}, dup_q=f"CarrierName={q_str(carrier_name)}",
                          extra=extra, dry_run=dry_run, confirm_prod=confirm_prod, allow_duplicate=allow_duplicate)


def add_carrier_ship_method(carrier_id: int, service_level_code: str, mode_of_transport_code: str,
                            extra: dict | None = None, dry_run: bool = True, confirm_prod: str = "") -> dict:
    """Step 2: add a shipping method to a carrier. Codes from lookups WSH_SERVICE_LEVELS / WSH_MODE_OF_TRANSPORT
    (lookup_values). The ShipMethodCode is generated by Oracle (read it from the result)."""
    return create_checked(f"carriers/{carrier_id}/child/shippingMethods",
                          {"ServiceLevelCode": service_level_code, "ModeOfTransportCode": mode_of_transport_code},
                          dup_q=f"ServiceLevelCode={q_str(service_level_code)} and ModeOfTransportCode={q_str(mode_of_transport_code)}",
                          extra=extra, dry_run=dry_run, confirm_prod=confirm_prod)


def enable_ship_method_on_org(carrier_id: int, ship_method_code: str, organization_code: str, dry_run: bool = True,
                              confirm_prod: str = "") -> dict:
    """Step 3: assign a carrier shipping method to an inventory organization (= enable the carrier on the org)."""
    return create_checked(f"carriers/{carrier_id}/child/shippingMethods/{ship_method_code}/child/organizationAssociations",
                          {"OrganizationCode": organization_code}, dup_q=f"OrganizationCode={q_str(organization_code)}",
                          dry_run=dry_run, confirm_prod=confirm_prod)


TOOLS = [find_inventory_org, create_carrier, add_carrier_ship_method, enable_ship_method_on_org]
